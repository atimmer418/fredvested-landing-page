package com.fredvested.web.email;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fredvested.web.service.EmailTemplates;
import org.springframework.context.annotation.Profile;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.Set;

/**
 * Dev-only preview of the v2 emails in a browser (never on prod: @Profile("!prod")).
 * The projection comes from one of the bundled sample files (email/samples/*.json,
 * generated by the calculator itself) chosen by name from an allow-list, never from
 * query numbers: no projection math in Java. The browser cannot show a cid image,
 * so the preview rewrites the chart's src to the PNG endpoint below; the sent
 * HTML is untouched.
 */
@RestController
@Profile("!prod")
@RequestMapping("/api/dev/email-preview")
public class EmailPreviewController {

    public static final Set<String> SAMPLES = Set.of(
            "sample", "existing-100k-optimistic", "short-horizon", "long-horizon",
            "target-under-1m", "target-over-5m", "stake-lever", "stake-hidden");
    static final String UNSUBSCRIBE_URL = "https://lpapi-dev.fredvested.com/api/waitlist/unsubscribe?token=preview";
    static final String CONFIRM_URL = "https://lpapi-dev.fredvested.com/api/waitlist/confirm?token=preview";
    static final String POSTAL_ADDRESS = "PO Box 2406, Rockville, MD 20847";

    private final ObjectMapper objectMapper;

    public EmailPreviewController(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    @GetMapping(produces = MediaType.TEXT_HTML_VALUE)
    public ResponseEntity<String> preview(@RequestParam(defaultValue = "welcome") String variant,
                                          @RequestParam(defaultValue = "sample") String sample) {
        if (!SAMPLES.contains(sample)) return ResponseEntity.badRequest().body("unknown sample");
        EmailTemplates.Rendered rendered = switch (variant) {
            case "welcome" -> PersonalizedWelcomeEmail.render(load(sample), UNSUBSCRIBE_URL, POSTAL_ADDRESS);
            case "welcome-fallback" -> PersonalizedWelcomeEmail.render(null, UNSUBSCRIBE_URL, POSTAL_ADDRESS);
            case "confirmation" -> EmailTemplates.confirmationV2(CONFIRM_URL, UNSUBSCRIBE_URL, 7, POSTAL_ADDRESS);
            default -> null;
        };
        if (rendered == null) return ResponseEntity.badRequest().body("unknown variant");
        String html = withChartUrl(rendered.html(), "/api/dev/email-preview/growth-chart.png?sample=" + sample);
        return ResponseEntity.ok().contentType(MediaType.TEXT_HTML).body(html);
    }

    @GetMapping(value = "/growth-chart.png", produces = MediaType.IMAGE_PNG_VALUE)
    public ResponseEntity<byte[]> chart(@RequestParam(defaultValue = "sample") String sample) {
        if (!SAMPLES.contains(sample)) return ResponseEntity.badRequest().build();
        return ResponseEntity.ok().contentType(MediaType.IMAGE_PNG).body(GrowthChartRenderer.render(load(sample)).bytes());
    }

    /** The sent HTML's cid reference swapped for a URL a browser can fetch (preview and on-disk fixtures only). */
    public static String withChartUrl(String html, String url) {
        return html.replace("src=\"" + PersonalizedWelcomeEmail.CID_REFERENCE + "\"", "src=\"" + EmailTemplateEngine.escape(url) + "\"");
    }

    /** A bundled sample projection by allow-listed name. */
    public Projection load(String sample) {
        if (!SAMPLES.contains(sample)) throw new IllegalArgumentException("unknown sample");
        try (InputStream in = EmailPreviewController.class.getClassLoader().getResourceAsStream("email/samples/" + sample + ".json")) {
            if (in == null) throw new IllegalStateException("sample missing: " + sample);
            return objectMapper.readValue(in, Projection.class);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
